"""
functions/cf_daily/status.py — T-1-0, шаг 2

Вычисление статуса по одному договору строго по `03_BUSINESS_SPEC.md §1`
(таблица порогов, `ADR-070`, боевые значения `ADR-057`).

Точка отсчёта — ПЛАНОВАЯ ДАТА ЗАКРЫТИЯ (`due_date` = `CONTRACTS.PLAN_CLOSE_DATE`),
не дата выдачи. `смещение = today − due_date` (дни): отрицательное до плановой
даты, положительное после.

Таблица порогов (`03 §1`), дословно:

| Смещение        | Статус             | Кто уведомляется   |
|-----------------|---------------------|---------------------|
| −7 и раньше     | 🟢 Активный          | —                   |
| −6 … +1         | 🟡 Внимание          | Бектур (manager)    |
| +2 … +15        | 🟠 Просрочен         | Бектур + Иса        |
| +16 … +31       | 🟠 Пре-маркетинг     | Эльхан + Иса        |
| +32 и далее     | 🔴 Реализация        | Эльхан + Иса        |
| ровно +39/+46/+62 | 🔴 (сводка/рекомендация, тот же статус) | Иса |

Строка «любое | 🔴 особый | Иса» (`03 §1`, предложение ниже floor) в эту функцию
НЕ входит: это не порог смещения, а событие сравнения цены с floor — вне scope
этой задачи (пороги цены — `T-1-0` их не считает, `03 §4`).

**Решение исполнителя (фиксируется здесь и в артефакте замера):** между именованными
порогами `+2`, `+16`, `+32` статус и адресат — СТУПЕНЬКА (staircase): держатся до
следующего порога включительно снизу. Дни `+39/+46/+62` — точечные события ВНУТРИ
диапазона 🔴 Реализация: статус (эмодзи/название) остаётся 🔴, но адресат сужается
до Исы РОВНО в эти дни (сводка/рекомендация — информационно), в остальные дни 🔴
адресат — Эльхан + Иса. Это единственное прочтение таблицы `03 §1`, дающее
непрерывную (без пропусков) функцию статуса на любое целое смещение — вход
`main.py` шага (г) обязан вернуть ответ на любую реальную дату, не только на
семь табличных точек.
"""

from __future__ import annotations

import datetime

# Адресаты по ролям `12_UX_CONTRACT.md` / `chat_id` (`11_INFRA_FACTS.md`).
MANAGER = "manager"  # Бектур
OWNER = "owner"  # Иса
ASSESSOR = "assessor"  # Эльхан

STATUS_GREEN = "🟢 Активный"
STATUS_YELLOW = "🟡 Внимание"
STATUS_ORANGE_OVERDUE = "🟠 Просрочен"
STATUS_ORANGE_PREMARKETING = "🟠 Пре-маркетинг"
STATUS_RED_REALIZATION = "🔴 Реализация"

# Точечные дни сводки/рекомендации внутри 🔴 (`03 §1`, последняя строка табличной
# части до floor-исключения): адресат сужается до Исы, статус не меняется.
RED_MILESTONE_OFFSETS = frozenset({39, 46, 62})


def compute_status(
    due_date: datetime.date, today: datetime.date
) -> tuple[str, tuple[str, ...]]:
    """Возвращает `(эмодзи/название статуса, кортеж адресатов)` по `03 §1`.

    `due_date` — `CONTRACTS.PLAN_CLOSE_DATE` (точка отсчёта, `ADR-070`).
    `today` — дата прогона.
    """
    offset = (today - due_date).days

    if offset <= -7:
        return STATUS_GREEN, ()
    if -6 <= offset <= 1:
        return STATUS_YELLOW, (MANAGER,)
    if 2 <= offset <= 15:
        return STATUS_ORANGE_OVERDUE, (MANAGER, OWNER)
    if 16 <= offset <= 31:
        return STATUS_ORANGE_PREMARKETING, (ASSESSOR, OWNER)
    # offset >= 32 -> 🔴 Реализация
    if offset in RED_MILESTONE_OFFSETS:
        return STATUS_RED_REALIZATION, (OWNER,)
    return STATUS_RED_REALIZATION, (ASSESSOR, OWNER)
