    echo "  repeat: второй проход не блокирует и пишет исход в замер — ОК"
else
    note_fail "форма: второй проход (ожидалось rc=0 плюс строка ПОВТОР-ВОЗВРАТ в замере, rc=${RT_RC})"
    printf '%s\n' "$RT_OUT" | sed 's/^/      /'
    [ -f "$RT/.claude/answer_check.log" ] && sed 's/^/      лог: /' "$RT/.claude/answer_check.log"
fi
rm -rf "$RT"

# --- первый проход по тому же тексту: обязан ВЕРНУТЬ (иначе прошлый кейс зелен впустую) ---
RT="$(mktemp -d)"; mkdir -p "$RT/.claude"
printf '%s\n' \
  '{"type":"assistant","message":{"content":[{"type":"text","text":"Разобрался с задачей, ниже подробности по шагам."}]}}' \
  > "$RT/transcript.jsonl"
CASE_NUM=$((CASE_NUM+1))
RT_OUT="$(cd "$RT" && printf '{"stop_hook_active":false,"transcript_path":"%s/transcript.jsonl"}' "$RT" | bash "$AC" 2>&1)"; RT_RC=$?
if [ "$RT_RC" -eq 2 ] && grep -q '	ВОЗВРАТ	' "$RT/.claude/answer_check.log" 2>/dev/null; then
    echo "  hook: первый проход возвращает ответ кодом 2 и пишет строку замера — ОК"
else
    note_fail "форма: первый проход через хук (ожидалось rc=2 плюс строка ВОЗВРАТ в замере, rc=${RT_RC})"
    printf '%s\n' "$RT_OUT" | sed 's/^/      /'
fi
rm -rf "$RT"

# --- отказ проверки громкий, но не блокирующий ------------------------------
# Транскрипт не разобран → работа НЕ блокируется, но причина названа строкой. Тихо
# отключившаяся проверка хуже отсутствующей: правило считается исполняемым, а исполнителя нет.
RT="$(mktemp -d)"; mkdir -p "$RT/.claude"
CASE_NUM=$((CASE_NUM+1))
RT_OUT="$(cd "$RT" && printf '{"transcript_path":"%s/нет-такого-файла.jsonl"}' "$RT" | bash "$AC" 2>&1)"; RT_RC=$?
if [ "$RT_RC" -eq 0 ] && printf '%s' "$RT_OUT" | grep -q 'НЕ проверена'; then
    echo "  fail-loud: отказ разбора назван строкой и работу не блокирует — ОК"
else
    note_fail "форма: отказ разбора (ожидалось rc=0 плюс строка «НЕ проверена», rc=${RT_RC})"
    printf '%s\n' "$RT_OUT" | sed 's/^/      /'
fi
rm -rf "$RT"

# --- гигиена замера: прогон --text в реальный лог не пишет -------------------
CASE_NUM=$((CASE_NUM+1))
AC_LOG_BEFORE=$( [ -f "${repo_root}/.claude/answer_check.log" ] && wc -l < "${repo_root}/.claude/answer_check.log" | tr -d ' ' || echo 0 )
LOCTMP="$(mktemp)"; printf '%s\n' 'мусор без шапки' > "$LOCTMP"
( cd "$repo_root" && LC_ALL=C bash "$AC" --text "$LOCTMP" ) >/dev/null 2>&1
rm -f "$LOCTMP"
AC_LOG_AFTER=$( [ -f "${repo_root}/.claude/answer_check.log" ] && wc -l < "${repo_root}/.claude/answer_check.log" | tr -d ' ' || echo 0 )
if [ "$AC_LOG_BEFORE" = "$AC_LOG_AFTER" ]; then
    echo "  hygiene: прогон --text в замер не попал (${AC_LOG_BEFORE} строк до и после) — ОК"
else
    note_fail "форма: прогон --text попал в замер (${AC_LOG_BEFORE} → ${AC_LOG_AFTER} строк)"
fi

# --- фикстура больше буфера пайпа -------------------------------------------
# Проверка донора умирала по SIGPIPE на входе больше 64 КБ и была зелёной на коротких
# фикстурах: длинный ответ проходил бы вообще без проверки. Кейс это ловит.
CASE_NUM=$((CASE_NUM+1))
BIGF="$(mktemp)"
{
    printf '%s\n' 'Сделано: длинный ответ.' 'Нужно от владельца: ничего.' 'Рекомендация: нет.' ''
    i=1; while [ $i -le 8000 ]; do printf -- '- строка номер %d\n' "$i"; i=$((i+1)); done
} > "$BIGF"
BIG_OUT="$(bash "$AC" --text "$BIGF" 2>&1)"; BIG_RC=$?
rm -f "$BIGF"
if [ "$BIG_RC" -eq 2 ] && printf '%s' "$BIG_OUT" | grep -q 'ФОРМА-3'; then
    echo "  bigfile: фикстура на 8000 строк разобрана целиком, не смерть по SIGPIPE — ОК"
else
    note_fail "форма: фикстура больше буфера пайпа (ожидалось rc=2 плюс ФОРМА-3, rc=${BIG_RC})"
    printf '%s\n' "$BIG_OUT" | head -5 | sed 's/^/      /'
fi
# ===========================================================================
echo
echo "=== ИТОГ САМОТЕСТА ==="
echo "кейсов проверено: ${CASE_NUM}"
echo "провалено ${FAILED}"
if [ "$FAILED" -eq 0 ]; then
    exit 0
else
    exit 1
fi
