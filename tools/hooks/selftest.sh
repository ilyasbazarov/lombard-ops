# БАТАРЕЯ 2 — форма ответа владельцу (tools/hooks/answer_check.sh; ADR-073, ADR-074).
#
# Признак правила-останова проверяется НЕГАТИВНЫМ прогоном: «ответ прошёл, нарушений нет»
# не удостоверяет ничего, потому что положительная ветка наступает всегда. Кейсы `fail` —
# по одному на каждый БЛОКИРУЮЩИЙ признак. Кейсы `pass` здесь не украшение: они несут вторую
# половину признака — законный ответ, который проверка ОБЯЗАНА пропустить. Самотест, написанный
# одной рукой с признаком, иначе закрепляет эталоном текущее поведение, а не корректность:
# у донора метода ровно так три законных ответа были машинно возвращены в поле за сутки.
# Признак и кейсы правятся ОДНИМ коммитом.
# Гоняется в обеих локалях по тому же мотиву, что батарея 1.
# ===========================================================================
AC="${repo_root}/tools/hooks/answer_check.sh"
[ -f "$AC" ] || { echo "ОШИБКА: не найден ${AC}"; exit 2; }

echo
echo "########## БАТАРЕЯ 2: форма ответа владельцу ##########"

ac_case() {  # $1 ожидание pass|fail · $2 имя · stdin — текст ответа
    local expect="$1" name="$2" f rc out
    CASE_NUM=$((CASE_NUM+1))
    f="$(mktemp)"; cat > "$f"
    out="$(LC_ALL="$LOC" LANG="$LOC" bash "$AC" --text "$f" 2>&1)"; rc=$?
    rm -f "$f"
    # Смерть по сигналу (rc > 128) — ПРОВАЛ даже в кейсе, ожидавшем отказ: проверка упала,
    # но ни одной причины не назвала, а это тихий отказ под видом срабатывания.
    if [ "$rc" -gt 128 ]; then
        note_fail "форма[$LOC] ${name}: проверка умерла по сигналу (rc=${rc})"
        return
    fi
    if { [ "$expect" = pass ] && [ "$rc" -eq 0 ]; } || { [ "$expect" = fail ] && [ "$rc" -eq 2 ]; }; then
        echo "  ${expect}: ${name} — ОК"
    else
        note_fail "форма[$LOC] ${name}: ожидалось ${expect}, rc=${rc}"
        printf '%s\n' "$out" | sed 's/^/      /'
    fi
}

ac_warn() {  # $1 ожидаемый код предупреждения · $2 имя · stdin — текст ответа
    # Предупредительный слой: ответ ПРОХОДИТ (rc=0), но вердикт напечатан. Проверяются оба
    # свойства сразу: пропуск без вердикта — тихий отказ, вердикт с возвратом — ровно тот
    # дефект, ради которого слой и разведён (машинное наказание за исполнение принятых правил).
    local code="$1" name="$2" f rc out
    CASE_NUM=$((CASE_NUM+1))
    f="$(mktemp)"; cat > "$f"
    out="$(LC_ALL="$LOC" LANG="$LOC" bash "$AC" --text "$f" 2>&1)"; rc=$?
    rm -f "$f"
    if [ "$rc" -eq 0 ] && printf '%s' "$out" | grep -q "$code"; then
        echo "  warn: ${name} — ОК (${code})"
    else
        note_fail "форма[$LOC] ${name}: ожидалось rc=0 плюс вердикт ${code}, rc=${rc}"
        printf '%s\n' "$out" | sed 's/^/      /'
    fi
}

