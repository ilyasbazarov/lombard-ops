#!/usr/bin/env bash
# tools/hooks/answer_judge.sh — судья упаковки смысла (05 §I; ADR-074 §6).
#
# Зачем. Форма ответа машине поддаётся целиком, упаковка смысла — нет: «отдал ли ответ готовое
# ядро или скорлупу» есть суждение, а не формат. Детерминированные признаки в answer_check.sh
# ловят два грубых класса (вывод в конце, журнал действий); остальное видит только модель.
#
# Режим ПРЕДУПРЕДИТЕЛЬНЫЙ всегда: ответ не блокируется никогда, вердикт уходит в замер.
# Мотив — судья недетерминирован, а ложный возврат дороже пропущенного дефекта.
#
# ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ, и это решение, а не недоделка (ADR-074 §6). Судья есть отдельный запуск
# модели на КАЖДЫЙ ответ роли; расход у проекта-донора замерен не был, и включение сплошняком
# покупает вердикт по одному ответу ценой замера за десяток сессий. Поэтому:
#   1) молчит, пока нет файла-выключателя .claude/answer_judge.on;
#   2) даже включённый судит ВЫБОРКУ — каждый N-й ответ (N в .claude/answer_judge.on, по
#      умолчанию 5): ценность судьи в замере за период, а не в вердикте по одному ответу.
# Порядок включения: авторизовать CLI (claude → /login), затем `echo 5 > .claude/answer_judge.on`.
# Критерий приёмки включения — НЕ факт включения и не --selfcheck, а негативный прогон на
# намеренно плохо упакованном ответе с файлом-носителем в reference/.
#
# Рекурсия закрыта переменной ANSWER_JUDGE_INNER: внутренний вызов работает в том же каталоге,
# видит тот же .claude/settings.json и без неё дёрнул бы хук Stop на своём же ответе.
set -u

DIR="$(cd "$(dirname "$0")" && pwd)"
LOG=".claude/answer_check.log"
SWITCH=".claude/answer_judge.on"
MODEL="${ANSWER_JUDGE_MODEL:-claude-haiku-4-5-20251001}"

log() { [ -d .claude ] && printf '%s\n' "$1" >> "$LOG" 2>/dev/null; return 0; }
stamp() { date -u '+%Y-%m-%dT%H:%M:%SZ'; }

[ "${ANSWER_JUDGE_INNER:-0}" = "1" ] && exit 0        # рекурсия
SELF=0; [ "${1:-}" = "--selfcheck" ] && SELF=1
[ -f "$SWITCH" ] || [ "$SELF" = "1" ] || exit 0

# Выборка. Знаменатель читается из файла-выключателя; нечисло и пусто дают 5.
if [ "$SELF" = "0" ]; then
  EVERY=$(tr -dc '0-9' < "$SWITCH" 2>/dev/null | head -c 3)
  [ -n "$EVERY" ] || EVERY=5
  [ "$EVERY" -gt 0 ] 2>/dev/null || EVERY=5
  SEEN=$(grep -c '	' "$LOG" 2>/dev/null || echo 0)
  [ $(( SEEN % EVERY )) -eq 0 ] || exit 0
fi

command -v claude >/dev/null 2>&1 || {
  printf 'answer_judge: CLI claude не найден, судья пропущен\n' >&2
  log "$(stamp)	СУДЬЯ-ОТКАЗ	CLI не найден"; exit 0; }
command -v python3 >/dev/null 2>&1 || { log "$(stamp)	СУДЬЯ-ОТКАЗ	нет python3"; exit 0; }

RUBRIC='Ты проверяешь ЧУЖОЙ ответ роли владельцу проекта lombard-ops по правилу упаковки смысла.
Правило: ответ обязан отдавать готовый смысловой результат, а не сырьё, из которого читатель
соберёт результат сам. Проверь семь вещей:
1. вывод стоит РАНЬШЕ доказательства, а не после цепочки фактов;
2. причинно-следственную связь сформулировал автор, а не оставил читателю сопоставлять два места;
3. это результат, а не журнал собственных действий;
4. числа выведены только те, что меняют вывод или нужны для решения владельца;
5. каждый абзац несёт одну смысловую операцию;
6. коды и номера работают на понимание, а не на демонстрацию точности;
7. работа не переложена на владельца: то, что снимается чтением репозитория или замером,
   снято автором, значения подставлены, выбор сопровождён рекомендацией.
Ответь РОВНО одной строкой без пояснений.
Если нарушений нет: OK
Если есть: НЕ ОК: <дословная строка-нарушитель из ответа> — <номер пункта и в чём дело>
Разбираемый ответ ниже, между маркерами.'

if [ "$SELF" = "1" ]; then
  TXT=$(mktemp); printf '%s\n' 'Сделано: ничего.' 'Нужно от владельца: ничего.' 'Рекомендация: ничего.' > "$TXT"
else
  EXTRACT="$DIR/answer_extract.py"
  [ -f "$EXTRACT" ] || exit 0
  TXT=$(mktemp)
  python3 "$EXTRACT" "$TXT"; rc=$?
  [ "$rc" -eq 0 ] || { rm -f "$TXT"; exit 0; }        # повторный заход либо нечего разбирать
  [ -s "$TXT" ] || { rm -f "$TXT"; exit 0; }
fi

VERDICT=$(
  { printf '%s\n\n===ОТВЕТ===\n' "$RUBRIC"; cat "$TXT"; printf '\n===КОНЕЦ===\n'; } \
  | ANSWER_JUDGE_INNER=1 claude -p --model "$MODEL" 2>&1 | tr '\n' ' ' | sed 's/[[:space:]]*$//'
)
rm -f "$TXT"

case "$VERDICT" in
  ""|*"Not logged in"*|*"Please run /login"*)
    printf 'answer_judge: CLI claude не авторизован — судья не работает. Порядок включения в шапке %s\n' "$DIR/answer_judge.sh" >&2
    log "$(stamp)	СУДЬЯ-ОТКАЗ	CLI не авторизован"
    exit 0 ;;
  OK*|ОК*)
    log "$(stamp)	СУДЬЯ	OK"
    [ "$SELF" = "1" ] && echo "answer_judge: судья отвечает, вердикт «$VERDICT»"
    exit 0 ;;
esac

# Вердикт печатается строкой-нарушителем, а не меткой: метка непроверяема.
printf 'СУДЬЯ УПАКОВКИ (предупреждение, ответ не блокируется):\n  %s\n' "$VERDICT" >&2
log "$(stamp)	СУДЬЯ-ЗАМЕЧАНИЕ	$VERDICT"
exit 0
