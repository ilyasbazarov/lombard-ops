#!/usr/bin/env bash
# tools/hooks/answer_check.sh — машинная проверка формы ответа владельцу (05 §I; ADR-073, ADR-074).
#
# Зачем. Текст владельцу — единственный артефакт проекта, который не лежит в репозитории и
# потому не виден ни pre-commit хуку, ни самотесту. Конвенция называла язык ответов «единственным
# законом проекта без механической проверки» — этот скрипт снимает эту строку: хук Stop читает
# ГОТОВЫЙ ответ и возвращает его модели на переписывание ДО того, как владелец его прочитал.
# Отчёт владельцу о нарушении формы бесполезен: он уже прочитал плохой ответ.
#
# Режимы запуска:
#   (без аргументов)  — хук Stop: JSON на stdin, текст берётся из transcript_path
#   --text <файл>     — проверка готового текста из файла (самотест; в замер НЕ пишет)
#
# ДВА СЛОЯ СТРОГОСТИ (ADR-074 §2). Блокирующий слой возвращает ответ: только признаки, которые
# НЕ МОГУТ сработать на содержании, предписанном другим принятым правилом. Предупредительный
# слой печатает вердикт и пишет его в замер, ответ не возвращает: туда уходит всё, что
# неотличимо от законного содержания (плотность чисел — строка приёмки и счётчик стенд-апа;
# плотность кодов — таблица задач, которую ADR-043 прямо ТРЕБУЕТ; просьба к владельцу — действие
# класса B исполняет только он; плейсхолдер — цитата шаблона брифа законна).
# Норма: признак, наказывающий исполнение принятого правила, переводится в предупредительный
# слой ЦЕЛИКОМ, а не обкладывается исключениями по одному.
#
# Коды выхода: 0 — форма сошлась, либо сработал только предупредительный слой, либо это
# повторный заход, либо внутренний отказ самой проверки; 2 — нарушение блокирующего слоя,
# stderr уходит модели и она переписывает ответ.
#
# ОТКАЗ ПРОВЕРКИ НЕ ТИХИЙ (05 §I, ритуал старта п.4): любой внутренний сбой печатается в stderr
# и дописывается в .claude/answer_check.log, но работу НЕ блокирует. Тихо отключившаяся проверка
# хуже отсутствующей: правило считается исполняемым, а исполнителя нет.
set -u

note() {
  printf 'answer_check: %s\n' "$*" >&2
  [ -d .claude ] && printf '%s\n' "answer_check: $*" >> .claude/answer_check.log 2>/dev/null
  return 0
}

# Локаль задаётся явно (тот же мотив, что у самотеста хука коммита): под байтовой семантикой
# классы символов в разборе кириллицы занижаются МОЛЧА, а вердикт печатается тот же самый.
for cand in ru_RU.UTF-8 en_US.UTF-8 C.UTF-8; do
  if locale -a 2>/dev/null | grep -qix -e "$cand" -e "${cand/UTF-8/utf8}"; then
    export LC_ALL="$cand"; break
  fi
done

TMPS=""
trap '[ -n "$TMPS" ] && rm -f $TMPS' EXIT

MODE=hook                   # --text: самотест и разовая проверка, в замер не идёт
REPEAT=0                    # второй проход по одному ответу: предупредительный (ADR-074 §3)
if [ "${1:-}" = "--text" ]; then
  MODE=text
  TXT="${2:-}"
  [ -f "$TXT" ] || { note "не найден файл текста '${2:-}'"; exit 0; }
else
  command -v python3 >/dev/null 2>&1 || { note "нет python3, форма ответа НЕ проверена"; exit 0; }
  EXTRACT="$(cd "$(dirname "$0")" && pwd)/answer_extract.py"
  [ -f "$EXTRACT" ] || { note "не найден $EXTRACT, форма ответа НЕ проверена"; exit 0; }
  TXT=$(mktemp); TMPS="$TXT"
  python3 "$EXTRACT" "$TXT"; rc=$?
  case "$rc" in
    0) ;;
    4) REPEAT=1 ;;                                   # повторный заход: меряем, но не блокируем
    *) note "транскрипт не разобран, форма ответа НЕ проверена"; exit 0 ;;
  esac
  [ -s "$TXT" ] || exit 0                            # текста нет — проверять нечего
fi

# ── разбор текста одним проходом ────────────────────────────────────────────────
NUM=0                       # порядковый номер непустой строки
H1=""; H2=""; H3=""
AFTER=0                     # непустых строк после шапки (лимит 05 §I)
PARA=0; MAXPARA=0; MAXPARA_AT=""
FENCE=0
MACHINE=""                  # первая напечатанная в чат строка машинной части
FORKS=0                     # блоков развилки; каждый расширяет лимит
RECS=0                      # строк рекомендации ПОСЛЕ шапки (дословное «рекомендую»)
LASTLINE=""                 # последняя непустая строка — ловит вывод, спрятанный в конец
JOURNAL=0                   # строк-шагов журнала действий
TELEM=""; CODES=""          # первые строки-нарушители: плотность чисел и кодов
ASKS=""; PLACE=""           # первые строки-нарушители: перекладывание и плейсхолдер

while IFS= read -r raw || [ -n "$raw" ]; do
  line=$(printf '%s' "$raw" | sed 's/[[:space:]]*$//')
  trimmed=$(printf '%s' "$line" | sed 's/^[[:space:]]*//')

  case "$trimmed" in '```'*) FENCE=$((1-FENCE)); PARA=0; continue;; esac
  [ -n "$trimmed" ] || { PARA=0; continue; }

  NUM=$((NUM+1))
  norm=$(printf '%s' "$trimmed" | tr -d '*#`' | sed 's/^[[:space:]]*//')

  case "$NUM" in
    1) H1="$norm" ;;
    2) H2="$norm" ;;
    3) H3="$norm" ;;
    *) AFTER=$((AFTER+1)) ;;
  esac

  # Носители машинной части, напечатанные в чат (05 §III: их место — файлы репозитория
  # и описание коммита; сессия применяет свой блок на диск сама с ADR-018/ADR-020).
  if [ -z "$MACHINE" ]; then
    case "$trimmed" in
      '=== SESSION LOG'*|'=== END SESSION'*|'## SESSION_LOG'*|'## STATE_PATCH'*|\
      '## INFRA_PATCH'*|'## NEW_DECISIONS'*|'## NEW_CONVENTIONS'*|'# BRIEF · T-'*)
        MACHINE="$trimmed" ;;
    esac
  fi

  # ── признаки упаковки смысла и перекладывания, тот же проход ──
  LASTLINE="$trimmed"
  case "$norm" in "Развилка Р-"*) FORKS=$((FORKS+1)) ;; esac
  if [ "$NUM" -gt 3 ]; then
    case "$norm" in
      'рекомендую'*|'Рекомендую'*) RECS=$((RECS+1)) ;;
    esac
  fi
  case "$norm" in
    'Сначала '*|'Затем '*|'Потом '*|'Далее '*|'После этого '*|'После чего '*) JOURNAL=$((JOURNAL+1)) ;;
  esac

  # Строки таблиц и блоков кода из счёта плотности исключены: таблицу задач с
  # идентификаторами ADR-043 прямо ТРЕБУЕТ, и мерить её плотность значит мерить
  # исполнение правила. Это не исключение из признака, а его предмет.
  if [ "$FENCE" = "0" ]; then
    case "$trimmed" in '|'*) : ;; *)
      if [ -z "$TELEM" ]; then
        case "$trimmed" in
          *'/'*)
            n=$(printf '%s' "$trimmed" | grep -o '[0-9][0-9]*' | wc -l | tr -d ' ')
            [ "$n" -ge 5 ] && TELEM="$trimmed" ;;
        esac
      fi
      if [ -z "$CODES" ]; then
        c=$(printf '%s' "$trimmed" | grep -oE '(ADR|Q|T|M|RF)-[0-9]+' | wc -l | tr -d ' ')
        [ "$c" -ge 4 ] && CODES="$trimmed"
      fi
    ;; esac
    if [ -z "$ASKS" ]; then
      case "$norm" in
        *'уточни у'*|*'посмотри сам'*|*'проверь сам'*|*'найди сам'*|*'разберись сам'*|\
        *'подставь свой'*|*'подставь сюда'*|*'сам подставь'*|*'сам посмотри'*|*'сам найди'*)
          ASKS="$trimmed" ;;
      esac
    fi
    if [ -z "$PLACE" ]; then
      if printf '%s' "$trimmed" | grep -qE '<[A-ZА-Я_][A-ZА-Я_0-9]{2,}>|YOUR_[A-Z]|<ВСТАВЬ|<ЗАПОЛНИ|<укажи'; then
        PLACE="$trimmed"
      fi
    fi
  fi

  # Длина абзаца. Список, таблица, заголовок, цитата, строка внутри блока кода и
  # продолжение с отступом абзацем НЕ являются: правило бьёт по слитному тексту,
  # а не по структуре, иначе оно валит нормальный маркированный список.
  [ "$FENCE" = "0" ] || { PARA=0; continue; }
  case "$trimmed" in
    -*|'*'*|'|'*|'#'*|'>'*|'§'*|[0-9].*|[0-9][0-9].*|[0-9]')'*) PARA=0; continue;;
  esac
  case "$line" in '  '*|'	'*) continue;; esac
  PARA=$((PARA+1))
  if [ "$PARA" -gt "$MAXPARA" ]; then MAXPARA="$PARA"; MAXPARA_AT="$trimmed"; fi
done < "$TXT"

# ── вердикты: печатаются сами нарушения со строкой-нарушителем, а не метка ──────
# «FAIL: слишком длинно» непроверяемо; «абзац длиной 5 строк при лимите 3, начало: …»
# проверяемо и сразу говорит модели, что чинить. Каждый признак несёт код: коды копятся
# в .claude/answer_check.log и сворачиваются tools/answer_stats.sh — правило чинится
# по замеру, а не по памяти.
V=0; OUT=""; KEYS=""
W=0; WOUT=""; WKEYS=""

warn() { W=$((W+1)); WKEYS="$WKEYS,$1"; WOUT="$WOUT
  $W. [$1] $2"; }
viol() { V=$((V+1)); KEYS="$KEYS,$1"; OUT="$OUT
  $V. [$1] $2"; }

case "$H1" in "Сделано:"*) ;; *) viol ФОРМА-1 "строка 1 шапки не «Сделано:», а «${H1:-<пусто>}»";; esac
case "$H2" in "Нужно от владельца:"*) ;; *) viol ФОРМА-1 "строка 2 шапки не «Нужно от владельца:», а «${H2:-<пусто>}»";; esac

REC=""
case "$H3" in
  "Рекомендация:"*)
    REC=$(printf '%s' "$H3" | sed 's/^Рекомендация:[[:space:]]*//')
    if [ -z "$REC" ]; then
      viol ФОРМА-2 "строка «Рекомендация:» пуста"
    else
      # Альтернация целыми словами, а не класс вида [Сс]: bracket-выражение с кириллицей
      # распадается на байты под байтовой семантикой и молча не срабатывает.
      case "$REC" in
        'см. ниже'*|'См. ниже'*|'ниже'*|'Ниже'*|'в тексте'*|'В тексте'*|'—'|'-')
          viol ФОРМА-2 "строка «Рекомендация:» отсылает вниз вместо содержания: «${REC}»";;
      esac
    fi ;;
  *) viol ФОРМА-1 "строка 3 шапки не «Рекомендация:», а «${H3:-<пусто>}»";;
esac

# Лимит расширяется блоками развилки: решение владельца требует вариантов, последствий и
# рекомендации, и сжимать его до тезиса — потеря существенного. Развилок больше двух в одном
# ответе не подаётся: это сигнал, что сессию надо делить, а не что ответ надо резать.
LIMIT=25
if [ "$FORKS" -gt 0 ]; then
  n=$FORKS; [ "$n" -gt 2 ] && n=2
  LIMIT=$((25 + 12 * n))
fi
[ "$FORKS" -le 2 ] || viol ФОРМА-3 "развилок в одном ответе $FORKS при пределе 2: лишние переносятся в следующую сессию"
[ "$AFTER" -le "$LIMIT" ] || viol ФОРМА-3 "текст владельцу после шапки — $AFTER непустых строк при лимите $LIMIT (развилок $FORKS): лишнее уходит в файл репозитория или в следующую сессию"
[ "$MAXPARA" -le 3 ] || viol ФОРМА-4 "абзац длиной $MAXPARA строк при лимите 3, начало: «${MAXPARA_AT}»"
[ -z "$MACHINE" ] || viol ФОРМА-5 "машинная часть напечатана в чат, строка «${MACHINE}»: её носители — файлы репозитория и описание коммита"

# ── упаковка смысла: признаки косвенные, но каждый предъявляет строку ───────────
case "$LASTLINE" in
  'Поэтому'*|'Таким образом'*|'Итого'*|'Следовательно'*|'Отсюда'*|'Значит,'*|'В итоге'*|'Вывод:'*)
    viol УПАКОВКА-1 "вывод спрятан в последнюю строку: «${LASTLINE}» — он должен стоять до доказательства";;
esac
[ "$JOURNAL" -lt 3 ] || viol УПАКОВКА-2 "журнал собственных действий вместо результата: строк-шагов «сначала/затем/потом/далее» — $JOURNAL"

# ── перекладывание работы на владельца (ADR-073 §3) ────────────────────────────
# Блокирующая часть держится на ДОСЛОВНЫХ строках, которые предписывает само правило:
# блок развилки открывается «Развилка Р-<n>.» и несёт строку, начинающуюся с «рекомендую».
# Без фиксированной формы проверке нечего считать, а владельцу — некуда смотреть.
if [ "$FORKS" -gt 0 ]; then
  case "$REC" in
    ''|'нет'|'Нет'|'нет.'|'Нет.'|'—'|'-')
      viol ПЕРЕКЛАД-1 "развилок $FORKS, а строка «Рекомендация:» пуста или «нет»: выбор без рекомендации есть перекладывание решения на владельца";;
  esac
  need=$FORKS; [ "$need" -gt 2 ] && need=2
  [ "$RECS" -ge "$need" ] || viol ПЕРЕКЛАД-2 "блоков развилки $FORKS, строк «рекомендую …» после шапки $RECS: каждая развилка обязана нести свою рекомендацию отдельной строкой"
fi

# ── предупредительный слой: вердикт в замер, ответ НЕ возвращается ──────────────
[ -z "$TELEM" ] || warn УПАКОВКА-3 "числа плотно, строка «${TELEM}»: проверь, каждое ли меняет вывод — строка приёмки и счётчик стенд-апа законны и возврата не требуют"
[ -z "$CODES" ] || warn УПАКОВКА-4 "плотность кодов в одной строке, «${CODES}»: идентификатор обоснования уходит в файл, в сообщении остаётся идентификатор действия"
[ -z "$ASKS" ] || warn ПЕРЕКЛАД-3 "работа предложена владельцу, строка «${ASKS}»: снимаемое чтением репозитория или замером делает сессия — владельцу остаётся только класс B и решение"
[ -z "$PLACE" ] || warn ПЕРЕКЛАД-4 "плейсхолдер в тексте владельцу, строка «${PLACE}»: значение, которое есть в контексте или в репозитории, подставляется, а не перекладывается поиском"

# ── замер: одна строка на ответ, время в UTC с суффиксом Z ─────────────────────
# Пишется ТОЛЬКО в режиме хука: прогоны --text это самотест, и в замере реальных ответов
# им не место — десятки фикстурных прогонов утопили бы картину. Метка ПОВТОР помечает
# второй проход по одному ответу: по паре строк ОТВЕТ→ПОВТОР виден ИСХОД возврата.
if [ "$MODE" = "hook" ] && [ -d .claude ]; then
  TS=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
  TAG=""; [ "$REPEAT" = "1" ] && TAG="ПОВТОР-"
  {
    if [ "$V" -gt 0 ]; then
      printf '%s\t%sВОЗВРАТ\t%d\t%s\n' "$TS" "$TAG" "$V" "${KEYS#,}"
    elif [ "$W" -gt 0 ]; then
      printf '%s\t%sПРЕДУПРЕЖДЕНИЕ\t%d\t%s\n' "$TS" "$TAG" "$W" "${WKEYS#,}"
    else
      printf '%s\t%sOK\t0\n' "$TS" "$TAG"
    fi
  } >> .claude/answer_check.log 2>/dev/null
fi

[ "$W" -eq 0 ] || printf 'ПРЕДУПРЕЖДЕНИЕ — ответ НЕ возвращён, вердикт ушёл в замер:%s\n' "$WOUT" >&2

[ "$V" -eq 0 ] && exit 0

# Второй проход: нарушение названо и посчитано, но выдача не блокируется — иначе пара
# «хук ↔ модель» уходит в цикл. На один ответ приходится ровно один принудительный переписыв.
if [ "$REPEAT" = "1" ]; then
  printf 'ПОВТОРНЫЙ ЗАХОД — ответ НЕ возвращён второй раз, нарушений %d ушло в замер:%s\n' "$V" "$OUT" >&2
  exit 0
fi

{
  printf 'ОТВЕТ ВОЗВРАЩЁН — нарушений %d (tools/hooks/answer_check.sh):%s\n' "$V" "$OUT"
  printf '\nПерепиши по 05 §I: шапка из трёх строк («Сделано:» · «Нужно от владельца:» ·\n'
  printf '«Рекомендация:»), вывод раньше доказательства, не более 25 строк после шапки\n'
  printf '(плюс 12 на каждую развилку), абзац не длиннее трёх строк, машинная часть в чат\n'
  printf 'не печатается, каждая развилка несёт строку «рекомендую …».\n'
  printf 'Сокращать существенное МОЛЧА запрещено — выброшенное назови одной строкой.\n'
} >&2
exit 2
