#!/usr/bin/env bash
# tools/hooks/answer_form_reminder.sh — напоминание формы ответа (05 §I; ADR-074 §5).
# Хук UserPromptSubmit: печатаемое уходит в контекст роли ПЕРЕД её работой.
#
# Смысл — тонус, а не исполнение. Правило лежит в конвенциях, но между стартом сессии и
# ответом проходят десятки шагов, и к моменту ответа оно уже вне окна внимания модели.
# Напоминание снижает частоту нарушений и признаком их отсутствия НЕ является: исполнитель
# правила — отдельный носитель, tools/hooks/answer_check.sh на хуке Stop.
set -u
cat <<'EOF'
[Форма ответа владельцу — 05 §I, проверяется машинно хуком Stop ДО того, как владелец увидит ответ]
Шапка ровно три строки: «Сделано:» · «Нужно от владельца:» · «Рекомендация:», каждая одной строкой, нечего написать — «нет».
Шапка идёт ПЕРВОЙ всегда, включая ответы с CONTEXT GAP, «СОДЕРЖИМОЕ НЕ ТО» и обязательными отчётами о проверках: маркер и отчёт идут сразу ПОСЛЕ шапки.
После шапки не более 25 непустых строк, плюс 12 на каждый блок развилки (развилок не больше двух). Абзац не длиннее трёх строк; перечень и таблица абзацем не считаются.
Вывод раньше доказательства: сначала что получилось и что это значит, фактура — после вывода как подтверждение. Связь формулируешь ты, а не читатель.
Развилка подаётся блоком: строка «Развилка Р-<n>. <суть>», варианты с последствиями, отдельная строка «рекомендую <вариант>, потому что <причина>». Выбор без рекомендации — перекладывание решения на владельца.
Работу не перекладывай: снимаемое чтением репозитория или замером снимай сам, значения из контекста подставляй, плейсхолдеров владельцу не выдавай. Владельцу остаётся класс B и решение.
Идентификатор ДЕЙСТВИЯ (задача, бриф, шаг) в сообщении обязателен; идентификаторы ОБОСНОВАНИЯ (номера решений, строк) уходят в файл, в сообщении одна строка со ссылкой.
Машинная часть (session-блок, патчи, брифы, содержимое файлов) в чат НЕ печатается: её носители — файлы репозитория и описание коммита.
EOF
